// The language cycles with one button (EN -> RU -> UZ -> EN) and is persisted
// in localStorage. Question/answer translations come from the DB
// (Question.translations JSON) and are picked by these helpers.

export type Lang = 'en' | 'ru' | 'uz';

export const NEXT_LANG: Record<Lang, Lang> = { en: 'ru', ru: 'uz', uz: 'en' };
export const LANG_LABEL: Record<Lang, string> = { en: 'EN', ru: 'RU', uz: 'UZ' };
export const LANG_NAME: Record<Lang, string> = { en: 'English', ru: 'Русский', uz: 'Oʻzbekcha' };
// Human names used server-side (explanation generation prompt)
export const LANG_FULL: Record<Lang, string> = { en: 'English', ru: 'Russian', uz: 'Uzbek (Latin script)' };

export function isLang(v: unknown): v is Lang {
  return v === 'en' || v === 'ru' || v === 'uz';
}

